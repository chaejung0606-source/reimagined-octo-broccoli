def test_mask_hides_names_in_reattach_lines_and_file_names():
    out = share_log.mask_text(REATTACH_LOG, keep=["202408470003"])
    # 이름은 찾은 자리 밖(적요 줄)에서도 가려진다 — 기록 전체에서
    for secret in ("진가람", "도해솔", "나래솔", "마루한", "은하별", "금보람", "SUNATULLAEV", "202612345"):
        assert secret not in out, secret
    assert "지출자료(AI개론)_(진○○_2026*****).pdf" in out
    assert "2026*****_도○○_근무일지.pdf" in out and "(나○○_2026*****_자료구조)" in out
    assert "── 진○○ (AI개론) (청구내역 2번째 줄" in out and "✓ 진○○ (AI개론) — 지움 5" in out
    assert "✓ 마○○ — 지움 3" in out and "✗ 은○○ (컴퓨터구조)" in out and "금○○ (운영체제) —" in out
    # 서류 낱말 · 업무 이름은 이름으로 보지 않는다 — 기록 전체에서 가려지면 글이 망가진다
    for kept in ("근로장학금_지급내역_공통증빙_2026.pdf", "장학금 — 이미 저장된", "── 과제 (모름)", "근무일지", "(AI개론)",
                 "[지원신청]", "2026-133"):
        assert kept in out, kept
    # 진단에 쓰는 것은 그대로 — 문서번호 · 결의번호 · 과제번호 · 날짜 · 금액
    for kept in ("202408470003-20261019-1", "결의번호 223", "과제 202408470003", "2026-10-19", "300,000원"):
        assert kept in out, kept


